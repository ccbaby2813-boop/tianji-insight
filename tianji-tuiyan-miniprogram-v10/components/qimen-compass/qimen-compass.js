    /**
     * 生成微星层（25颗静态暗星，纯深度提示）
     */
    _generateStarfield() {
      const size = this.data.size;
      const halfSize = size / 2;
      const dots = [];
      for (let i = 0; i < 25; i++) {
        const angle = Math.random() * Math.PI * 2;
        const radius = halfSize * (0.15 + Math.random() * 0.8);
        const x = halfSize + radius * Math.cos(angle);
        const y = halfSize + radius * Math.sin(angle);
        dots.push({
          x: x.toFixed(0),
          y: y.toFixed(0)
        });
      }
      this.setData({ starDots: dots });
    },

    _genItems(names, radius) {
      const count = names.length;
      const angleStep = 360 / count;
      const halfSize = this.data.size / 2;
      return names.map((name, i) => {
        const angle = (i * angleStep - 90) * Math.PI / 180;
        const x = halfSize + radius * Math.cos(angle);
        const y = halfSize + radius * Math.sin(angle);
        return {
          name,
          style: `position:absolute; left:${x}rpx; top:${y}rpx; transform:translate(-50%,-50%);`
        };
      });
    },

